"""Offline checks for switching archived A/B wheels through one profiling checkout."""
import importlib.util
from pathlib import Path
import tempfile
import unittest
from unittest import mock
import zipfile

ROOT = Path(__file__).resolve().parents[8]
SPEC = importlib.util.spec_from_file_location(
    "gdn_wheel_reference_test", ROOT / "tests/atk/chunk_gated_delta_rule_fwd/scripts/profile_performance.py")
collector = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(collector)
VENDOR = "opp/vendors/fla_npu_transformer"
KERNEL = VENDOR + "/op_impl/ai_core/tbe/kernel/ascend950/prepare.o"
OPAPI = VENDOR + "/op_api/lib/libcust_opapi.so"
WRAPPER = "ops/ascendc/_aclnn_ctypes.py"


class WheelReferenceContract(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(dir=Path(__file__).resolve().parent)
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.package = self.root / "site-packages/fla_npu"
        self.payload = {"__init__.py": b"# A\n", WRAPPER: b"# profile adapter\n",
                        OPAPI: b"same host library", KERNEL: b"A kernel",
                        VENDOR + "/op_impl/ai_core/tbe/config/ascend950/prepare.json": b"{}"}
        for relative, content in self.payload.items():
            path = self.package / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
        self.wheel = self.make_wheel("A.whl", self.payload)

    def make_wheel(self, filename, payload):
        path = self.root / filename
        with zipfile.ZipFile(path, "w") as archive:
            for relative, content in payload.items():
                archive.writestr("fla_npu/" + relative, content)
            archive.writestr("fla_npu-0.1.dist-info/METADATA", "Name: fla-npu\nVersion: 0.1\n")
        return path

    def test_archived_a_ignores_b_staging_and_records_identity(self):
        staging = self.root / "build/lib/fla_npu" / KERNEL
        staging.parent.mkdir(parents=True)
        staging.write_bytes(b"B kernel")
        cache = self.package / "__pycache__/adapter.pyc"
        cache.parent.mkdir()
        cache.write_bytes(b"generated bytecode")
        result = collector.verify_installed_wheel(self.wheel, self.package)
        self.assertEqual(result["sha256"], collector.file_sha256(self.wheel))
        self.assertEqual((result["distribution"], result["version"]), ("fla-npu", "0.1"))
        self.assertEqual(result["checked_files"], len(self.payload))
        self.assertEqual(result["checked_kernel_objects"], 1)

    def test_kernel_mismatch_rejected_even_when_opapi_matches(self):
        other = dict(self.payload, **{KERNEL: b"B kernel"})
        wheel_b = self.make_wheel("B.whl", other)
        with self.assertRaisesRegex(RuntimeError, "differs.*prepare.o"):
            collector.verify_installed_wheel(wheel_b, self.package)
        (self.package / KERNEL).write_bytes(other[KERNEL])
        self.assertEqual(collector.verify_installed_wheel(wheel_b, self.package)["mode"], "reference_wheel")
        with self.assertRaisesRegex(RuntimeError, "differs.*prepare.o"):
            collector.verify_installed_wheel(self.wheel, self.package)

    def test_python_and_config_mismatch_rejected(self):
        for relative in (WRAPPER, VENDOR + "/op_impl/ai_core/tbe/config/ascend950/prepare.json"):
            with self.subTest(relative=relative):
                path = self.package / relative
                path.write_bytes(b"stale installed content")
                with self.assertRaisesRegex(RuntimeError, "differs"):
                    collector.verify_installed_wheel(self.wheel, self.package)
                path.write_bytes(self.payload[relative])

    def test_missing_or_extra_native_file_rejected(self):
        path = self.package / KERNEL
        path.unlink()
        with self.assertRaisesRegex(RuntimeError, "missing"):
            collector.verify_installed_wheel(self.wheel, self.package)
        path.write_bytes(self.payload[KERNEL])
        path.with_name("stale.o").write_bytes(b"old kernel")
        with self.assertRaisesRegex(RuntimeError, "Unexpected installed native"):
            collector.verify_installed_wheel(self.wheel, self.package)

    def test_incomplete_wheel_rejected(self):
        for missing in (KERNEL, OPAPI):
            with self.subTest(missing=missing):
                payload = {name: value for name, value in self.payload.items() if name != missing}
                wheel = self.make_wheel("incomplete.whl", payload)
                with self.assertRaisesRegex(ValueError, "compiled kernel"):
                    collector.verify_installed_wheel(wheel, self.package)

    def test_invalid_or_duplicate_runtime_path_rejected(self):
        for relative in ("../outside.so", "/outside.so"):
            with self.subTest(relative=relative):
                payload = dict(self.payload, **{relative: b"invalid"})
                wheel = self.make_wheel("invalid.whl", payload)
                with self.assertRaisesRegex(ValueError, "Invalid runtime path"):
                    collector.verify_installed_wheel(wheel, self.package)
        with zipfile.ZipFile(self.wheel, "a") as archive:
            with self.assertWarns(UserWarning):
                archive.writestr("fla_npu/" + KERNEL, b"duplicate")
        with self.assertRaisesRegex(ValueError, "Duplicate runtime path"):
            collector.verify_installed_wheel(self.wheel, self.package)

    def test_missing_or_invalid_archive_rejected(self):
        with self.assertRaisesRegex(ValueError, "existing .whl"):
            collector.verify_installed_wheel(self.root / "missing.whl", self.package)
        broken = self.root / "broken.whl"
        broken.write_bytes(b"not a zip archive")
        with self.assertRaisesRegex(ValueError, "Invalid reference wheel archive"):
            collector.verify_installed_wheel(broken, self.package)

    def test_reference_mode_skips_staging_checker_and_logs_failures(self):
        log = self.root / "installed_artifacts.log"
        with mock.patch.object(collector, "run_logged") as run, mock.patch("builtins.print"):
            result = collector.verify_profile_artifacts(self.wheel, self.package / VENDOR, log, {})
            run.assert_not_called()
            self.assertEqual(result["mode"], "reference_wheel")
            self.assertIn(result["sha256"], log.read_text(encoding="utf-8"))
            (self.package / KERNEL).write_bytes(b"wrong kernel")
            with self.assertRaisesRegex(RuntimeError, "differs"):
                collector.verify_profile_artifacts(self.wheel, self.package / VENDOR, log, {})
            self.assertIn("verification failed", log.read_text(encoding="utf-8"))

    def test_default_mode_preserves_existing_staging_checker(self):
        log = self.root / "installed_artifacts.log"
        with mock.patch.object(collector, "run_logged") as run:
            result = collector.verify_profile_artifacts(None, self.package / VENDOR, log, {})
            run.assert_called_once()
            self.assertEqual(run.call_args.args[0][-1], "--python")
            self.assertIn("verify_libcust_opapi_md5.py", run.call_args.args[0][1])
            self.assertEqual(result, {"mode": "build_staging"})

    def test_cli_selects_reference_wheel(self):
        args = collector.parse_args(["--cases", "0", "--reference-wheel", str(self.wheel)])
        self.assertEqual(args.reference_wheel, self.wheel)
        self.assertEqual(args.cases, [0])
        self.assertIsNone(collector.parse_args([]).reference_wheel)


if __name__ == "__main__":
    unittest.main()
